# Build the embedded banner: resize the source art, knock the outer white
# background out to alpha (edge flood fill, so whites INSIDE the art stay), and
# emit src/asset.ts with a data: URL.
#
# The card can then be drawn on a frosted-glass panel or fully transparent,
# letting the page show through around the chibi and the frame.
import base64
import io
import os
import sys
from collections import deque

from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SOURCE = os.path.join(os.path.dirname(ROOT), "鲸鱼女仆进度条UI.png")
TARGET = os.path.join(ROOT, "src", "asset.ts")
WIDTH = int(sys.argv[1]) if len(sys.argv) > 1 else 2000
QUALITY = int(sys.argv[2]) if len(sys.argv) > 2 else 90
WHITE = 246  # a pixel counts as background when every channel is at least this
FEATHER = 26  # soft edge width in alpha units


def background_mask(image):
    """Flood fill white pixels connected to the image border."""
    width, height = image.size
    pixels = image.load()
    seen = bytearray(width * height)
    queue = deque()
    for x in range(width):
        for y in (0, height - 1):
            queue.append((x, y))
    for y in range(height):
        for x in (0, width - 1):
            queue.append((x, y))
    while queue:
        x, y = queue.popleft()
        index = y * width + x
        if seen[index]:
            continue
        r, g, b = pixels[x, y][:3]
        if min(r, g, b) < WHITE:
            continue
        seen[index] = 1
        if x > 0:
            queue.append((x - 1, y))
        if x + 1 < width:
            queue.append((x + 1, y))
        if y > 0:
            queue.append((x, y - 1))
        if y + 1 < height:
            queue.append((x, y + 1))
    return seen


def build():
    image = Image.open(SOURCE).convert("RGB")
    height = round(image.height * WIDTH / image.width)
    small = image.resize((WIDTH, height), Image.LANCZOS)
    mask = background_mask(small)

    # alpha: hard 0 on the filled background, feathered at its border so the
    # knock-out does not leave a white fringe around the character.
    alpha = Image.new("L", small.size, 255)
    alpha_px = alpha.load()
    for index, flag in enumerate(mask):
        if flag:
            alpha_px[index % WIDTH, index // WIDTH] = 0
    alpha = alpha.filter(ImageFilter.MinFilter(3))  # grow the hole by a pixel
    # blur only near the boundary: blend the soft edge back over the hard mask
    soft = alpha.filter(ImageFilter.GaussianBlur(FEATHER / 4))
    alpha = Image.composite(soft, alpha, alpha.point(lambda v: 255 if 0 < v < 255 else 0))

    rgba = small.convert("RGBA")
    rgba.putalpha(alpha)

    buffer = io.BytesIO()
    rgba.save(buffer, "WEBP", quality=QUALITY, method=6, alpha_quality=100)
    payload_bytes = buffer.getvalue()
    payload = base64.b64encode(payload_bytes).decode("ascii")

    with open(TARGET, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("// Generated by scripts/make-asset.py — do not edit by hand.\n")
        handle.write(
            f"// source: 鲸鱼女仆进度条UI.png -> {WIDTH}x{height} WebP q{QUALITY} with alpha, "
            f"{len(payload_bytes)} bytes\n"
        )
        handle.write(f"export const BANNER_WIDTH = {WIDTH};\n")
        handle.write(f"export const BANNER_HEIGHT = {height};\n")
        handle.write('export const BANNER_BG = "data:image/webp;base64,' + payload + '";\n')

    preview = os.path.join(ROOT, "test", "banner-alpha.png")
    rgba.save(preview, "PNG")
    print(f"{WIDTH}x{height} webp q{QUALITY} alpha: {len(payload_bytes)} bytes -> {os.path.getsize(TARGET)} bytes")
    print(f"preview: {preview}")


if __name__ == "__main__":
    build()
