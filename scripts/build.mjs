// Bundle src/app.tsx into the client module that DSH's loader executes.
// Bun produces an ES module; the loader expects a `window.__ModuleLoader__.load`
// wrapper whose factory receives `require`, so the bundle body is inlined into
// that factory and the trailing export block is dropped.
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const BUN = process.env.DSH_BUN || "C:\\Users\\Administrator\\.bun\\bin\\bun.exe";
const PYTHON =
  process.env.DSH_PYTHON ||
  "C:\\Users\\Administrator\\.dsh\\dsh-runtimes\\dsh-primary-runtime\\dependencies\\python\\python.exe";

const SRC = join(ROOT, "src", "app.tsx");
const ASSET = join(ROOT, "src", "asset.ts");
const TMP = join(ROOT, ".build");
const OUT = join(ROOT, "client.js");

mkdirSync(TMP, { recursive: true });

if (!readFileSync(ASSET, "utf8").includes("BANNER_BG")) {
  throw new Error("src/asset.ts is missing BANNER_BG; run scripts/make-asset.py first");
}

execFileSync(BUN, ["build", SRC, "--format=esm", "--target=browser", `--outfile=${join(TMP, "app.js")}`], {
  stdio: "inherit",
});

let body = readFileSync(join(TMP, "app.js"), "utf8");
const exportAt = body.lastIndexOf("\nexport {");
if (exportAt !== -1) body = body.slice(0, exportAt);
body = body.trimEnd();

const banner = `// dsh-month-timer client bundle — generated by scripts/build.mjs from src/app.tsx.
// Do not edit by hand; edit src/ and run \`bun scripts/build.mjs\`.
`;

const probe = (stage) => `;(function () {
  try { document.title = "MT:${stage}"; } catch (e) {}
  try {
    fetch("/_dsh/dsh-month-timer/beacon", { method: "POST", body: "${stage}", keepalive: true }).catch(function () {});
  } catch (e) {}
})();
`;

const client = `${banner}${probe("script")}window.__ModuleLoader__.load({
  id: "dsh-month-timer",
  factory(require) {
    ${probe("factory").trim()}
    const React = require("react");
${body
  .split("\n")
  .map((line) => (line ? "    " + line : line))
  .join("\n")}
    return {
      inject: ["slots", "locale"],
      apply(ctx) {
        try { document.title = "MT:apply"; } catch (e) {}
        mount(ctx);
      },
    };
  },
});
`;

writeFileSync(OUT, client, "utf8");
copyFileSync(join(TMP, "app.js"), join(TMP, "app.debug.js"));
console.log(`client.js: ${(client.length / 1024).toFixed(1)} KiB`);
